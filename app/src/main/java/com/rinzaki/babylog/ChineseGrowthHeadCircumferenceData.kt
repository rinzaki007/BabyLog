    private fun String.toGrowthRows(): List<GrowthStandardRow> = trimIndent()
        .lineSequence()
        .filter { it.isNotBlank() }
        .map { line ->
            val values = line.split('|').map(String::toFloat)
            require(values.size == 8) { "Invalid WS/T 423 head-circumference row: $line" }
            GrowthStandardRow(
                ageMonths = values[0].toInt(),
                percentiles = GrowthPercentiles(
                    values[1], values[2], values[3], values[4],
                    values[5], values[6], values[7]
                )
            )
        }
